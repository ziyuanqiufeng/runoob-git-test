def main():
    check_only = "--check" in sys.argv
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "config", "events.json")

    with open(path, "r", encoding="utf-8") as f:
        events = json.load(f)

    ids = {e["id"] for e in events}
    missing = ids - set(EVENT_TEXTS)
    extra = set(EVENT_TEXTS) - ids
    if missing:
        print(f"[FAIL] 以下事件缺少文案：{sorted(missing)}")
        return 1
    if extra:
        print(f"[FAIL] 文案中存在未知事件 id：{sorted(extra)}")
        return 1

    # 长度守门：每条 40~140 字，防止灌水或截断
    bad = []
    for eid, texts in EVENT_TEXTS.items():
        if len(texts) < 2:
            bad.append(f"{eid}: 变体不足 2 条")
        for t in texts:
            if not (40 <= len(t) <= 140):
                bad.append(f"{eid}: 单条长度 {len(t)} 越界")
    if bad:
        print("[FAIL] 文案质量守门未过：\n  " + "\n  ".join(bad))
        return 1

    if check_only:
        print(f"[OK] {len(events)} 个事件文案全部就位（check 模式，未写入）")
        return 0

    for e in events:
        e["descriptions"] = EVENT_TEXTS[e["id"]]

    with open(path, "w", encoding="utf-8") as f:
        json.dump(events, f, ensure_ascii=False, indent=2)
        f.write("\n")

    total = sum(len(t) for ts in EVENT_TEXTS.values() for t in ts)
    print(
        f"[OK] 已写入 {len(events)} 个事件的 descriptions"
        f"（{sum(len(v) for v in EVENT_TEXTS.values())} 条变体，共 {total} 字）"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
